import bcrypt from "bcryptjs";
import jwt from "jsonwebtoken";
import { env } from "../config/env.js";
import pool from "../config/mysql.js";

// Normal registration
const register = async (req, res) => {
  try {
    const { email, password, role, displayName } = req.body;

    // Validate required fields
    if (!email || !password || !role) {
      return res.status(400).json({
        message: "Email, password, and role are required",
      });
    }

    // Validate role
    if (role !== "learner" && role !== "professional") {
      return res.status(400).json({
        message: "Invalid role",
      });
    }

    // Check if account already exists
    const [existingAccountRows] = await pool.query(
      "SELECT account_id FROM accounts WHERE email = ?",
      [email]
    );

    if (existingAccountRows.length > 0) {
      return res.status(409).json({
        message: "Account already exists",
      });
    }

    // Hash password
    const hashedPassword = await bcrypt.hash(password, 10);

    // Create account
    const [accountResult] = await pool.query(
      "INSERT INTO accounts (email, password, role) VALUES (?, ?, ?)",
      [email, hashedPassword, role]
    );

    // This is the ID generated by the accounts table
    const accountId = accountResult.insertId;

    // Create role-specific profile
    if (role === "learner") {
      await pool.query(
        "INSERT INTO learner ( account_id, name) VALUES (?, ?)",
        [accountId, displayName || null]
      );
    }

    if (role === "professional") {
      await pool.query(
        "INSERT INTO professionals (account_id, name) VALUES (?, ?)",
        [accountId, displayName || null]
      );
    }

    // Create JWT
    const token = jwt.sign(
      {
        id: accountId.toString( ),
        email,
        role,
      },
      env.jwt_secret,
      {
        expiresIn: "7d",
      }
    );

    // Store JWT in HTTP-only cookie
    res.cookie("token", token, {
      httpOnly: true,
      secure: env.nodeEnv === "production",
      sameSite: env.nodeEnv === "production" ? "none" : "lax",
      maxAge: 7 * 24 * 60 * 60 * 1000,
    });

    return res.status(201).json({
      message: "Account registered successfully",
      token,
    });

  } catch (err) {
    console.error("Registration error:", err);

    return res.status(500).json({
      message: "Server error during registration",
    });

  }
};

// Normal email/password login
const login = async (req, res) => {
  try {
    const { email, password } = req.body;

    if (!email || !password) {
      return res.status(400).json({
        message: "Email and password are required",
      });
    }

    // Find account using email
    const [rows] = await pool.query(
      "SELECT account_id, email, password, role FROM accounts WHERE email = ?",
      [email]
    );

    const account = rows[0];

    if (!account) {
      return res.status(401).json({
        message: "Account does not exists",
      });
    }

    // Check whether this is a password-based account
    if (!account.password) {
      return res.status(400).json({
        message: "This account uses Google login. Please continue with Google.",
      });
    }

    // Compare entered password with hashed password
    const isMatch = await bcrypt.compare(
      password,
      account.password
    );

    if (!isMatch) {
      return res.status(401).json({
        message: "Invalid credentials",
      });
    }

    // Create JWT using the account ID
    const token = jwt.sign(
      {
        id: account.account_id.toString(),
        email: account.email,
        role: account.role,
      },
      env.jwt_secret,
      {
        expiresIn: "7d",
      }
    );

    // Store JWT in HTTP-only cookie
    res.cookie("token", token, {
      httpOnly: true,
      secure: env.nodeEnv === "production",
      sameSite: env.nodeEnv === "production" ? "none" : "lax",
      maxAge: 7 * 24 * 60 * 60 * 1000,
    });

    return res.status(200).json({
      message: "Account logged in successfully",
      token,
    });

  } catch (err) {
    console.error("Login error:", err);

    return res.status(500).json({
      message: "Server error during login",
    });
  }
};

// Google OAuth callback
const googleCallback = async (req, res) => {
  try {
    if (!req.user) {
      return res.status(401).json({
        message: "Google authentication failed",
      });
    }

    const googleUser = req.user;
    console.log("Google user:", googleUser);

    const email = googleUser.emails?.[0]?.value;
    
    if (!email) {
      return res.status(400).json({
        message: "Google account email not available",
      });
    }

    const role = req.query.state;

    // Try to find existing account by email (like login/register)
    const [accounts] = await pool.query("SELECT * FROM accounts WHERE email = ?", [email]);
    let account = accounts[0];

    // If account does not exist, create a new learner account (like register)
    if (!account) {
      const [insertResult] = await pool.query(
        `INSERT INTO accounts (email, password,role) VALUES (?, ?, ?)`,
        [
          email,
          null, // No password for OAuth accounts
          role,
        ]
      );
      const accountId = insertResult.insertId;

      if (role === "learner") {
        await pool.query(
          "INSERT INTO learner (account_id, name) VALUES (?, ?)",
          [accountId, googleUser.displayName || null]
        );
      }

      if (role === "professional") {
        await pool.query(
          "INSERT INTO professionals (account_id, name) VALUES (?, ?)",
          [accountId, googleUser.displayName || null]
        );
      }

      const [createdRows] = await pool.query("SELECT * FROM accounts WHERE account_id = ?", [accountId]);
      account = createdRows[0];
    }

    // Create JWT just like login/register
    const token = jwt.sign(
      {
        id: account.account_id.toString(),
        email: account.email,
        role: account.role,
      },
      env.jwt_secret,
      {
        expiresIn: "7d",
      }
    );

    // Store JWT in HTTP-only cookie (same as login)
    res.cookie("token", token, {
      httpOnly: true,
      secure: env.nodeEnv === "production",
      sameSite: env.nodeEnv === "production" ? "none" : "lax",
      maxAge: 7 * 24 * 60 * 60 * 1000,
    });

    return res.status(200).json({
      message: "Account logged in successfully",
      token,
    });
  } catch (err) {
    console.error("Google authentication error:", err);

    return res.status(500).json({
      message: "Server error during Google authentication",
    });
  }
};

const logout = (req, res) => {
  try {

    const token = req.cookies.token

    res.clearCookie("token", {
      httpOnly: true,
      secure: process.env.NODE_ENV === "production",
      sameSite: process.env.NODE_ENV === "production" ? "none" : "lax",
    });
    return res.status(200).json({ message: "Logged out successfully" });
  } catch (err) {
    console.error("Logout error:", err);
    return res.status(500).json({ message: "Server error during logout" });
  }
};


export { register, login, googleCallback, logout };
